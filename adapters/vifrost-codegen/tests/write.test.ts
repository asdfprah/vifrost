import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { writeGeneratedFiles } from '../src/write.js'

let outputDir: string

beforeEach(async () => {
  outputDir = await mkdtemp(path.join(tmpdir(), 'vifrost-codegen-'))
})

afterEach(async () => {
  await rm(outputDir, { recursive: true, force: true })
})

describe('writeGeneratedFiles', () => {
  it('removes generated files of models no longer in the schema and keeps everything else', async () => {
    await writeFile(path.join(outputDir, 'User.ts'), '// Generated by @vifrost/codegen — do not edit by hand.\n')
    await writeFile(path.join(outputDir, 'helpers.ts'), 'export const helper = 1\n')
    await writeFile(path.join(outputDir, 'notes.md'), '// Generated by @vifrost/codegen\n')

    const result = await writeGeneratedFiles(outputDir, [
      { fileName: 'Product.ts', content: '// Generated by @vifrost/codegen — do not edit by hand.\n' },
      { fileName: 'index.ts', content: '// Generated by @vifrost/codegen — do not edit by hand.\n' },
    ])

    expect(result).toEqual({ written: ['Product.ts', 'index.ts'], removed: ['User.ts'] })
    expect((await readdir(outputDir)).sort()).toEqual(['Product.ts', 'helpers.ts', 'index.ts', 'notes.md'])
  })

  it('overwrites the files it generates again', async () => {
    await writeFile(path.join(outputDir, 'Product.ts'), '// Generated by @vifrost/codegen\nold\n')

    await writeGeneratedFiles(outputDir, [{ fileName: 'Product.ts', content: '// Generated by @vifrost/codegen\nnew\n' }])

    expect(await readFile(path.join(outputDir, 'Product.ts'), 'utf-8')).toContain('new')
  })

  it('creates the output directory when missing', async () => {
    const nested = path.join(outputDir, 'models')

    const result = await writeGeneratedFiles(nested, [{ fileName: 'index.ts', content: '// Generated by @vifrost/codegen\n' }])

    expect(result.written).toEqual(['index.ts'])
  })
})
