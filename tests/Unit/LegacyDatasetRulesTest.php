<?php

use App\Http\Controllers\CouponController;
use Illuminate\Database\Schema\Blueprint;
use Illuminate\Support\Facades\Route;
use Illuminate\Support\Facades\Schema;
use Vifrost\Laravel\SchemaExporter;
use Vifrost\Laravel\Tests\Fixtures\LegacyDatasetModels\Coupon;

require_once __DIR__ . '/../Support/LegacyDatasetControllers.php';

beforeEach(function () {
    config(['vifrost.models_path' => 'LegacyDatasetModels']);
    Route::get('api/coupon', [CouponController::class, 'index']);

    Schema::dropIfExists('legacy_coupons');
    Schema::create('legacy_coupons', function (Blueprint $table) {
        $table->id();
        $table->string('code');
        $table->integer('percent');
    });
    foreach ([['A', 10], ['B', 10], ['C', 25]] as [$code, $percent]) {
        Coupon::create(['code' => $code, 'percent' => $percent]);
    }
});

it('still serves datasets of controllers generated by 0.9.0', function () {
    $rows = test()->getJson('/api/coupon?' . http_build_query([
        'select' => 'percent',
        'aggregate' => ['total' => 'count'],
        'group' => 'percent',
        'sort' => 'percent',
        'limit' => 10,
    ]))->assertOk()->json();

    expect($rows)->toEqual([['percent' => 10, 'total' => 2], ['percent' => 25, 'total' => 1]]);
});

it('still exports the dataset rules of controllers generated by 0.9.0', function () {
    $dataset = SchemaExporter::build([Coupon::class])['models'][Coupon::class]['dataset'];

    expect(array_keys($dataset['columns']))->toBe(['code', 'percent'])
        ->and($dataset['aggregates'])->toBe(['count']);
});
